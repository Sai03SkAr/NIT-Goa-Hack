"""AI-generated media: what provenance metadata catches, what it must not flag, and why a fully generated card fails
anyway (no valid issuer signature)."""
import datetime as dt
import io
import json

import cv2
import numpy as np
import pytest

from app.modules.document import forensics, provenance, qr_sign

c2pa = pytest.importorskip("c2pa")


def _jpeg(text="ID") -> bytes:
    img = np.full((240, 320, 3), 190, np.uint8)
    cv2.putText(img, text, (100, 140), cv2.FONT_HERSHEY_SIMPLEX, 2, (30, 30, 30), 4)
    return cv2.imencode(".jpg", img)[1].tobytes()


def _chain():
    """A throwaway test CA and signing certificate (C2PA rejects self-signed signing certificates)."""
    from cryptography import x509
    from cryptography.hazmat.primitives import hashes, serialization
    from cryptography.hazmat.primitives.asymmetric import ec
    from cryptography.x509.oid import ExtendedKeyUsageOID, NameOID
    now = dt.datetime.now(dt.timezone.utc)
    ku = lambda sign, ca: x509.KeyUsage(digital_signature=sign, content_commitment=False, key_encipherment=False,  # noqa: E731
                                        data_encipherment=False, key_agreement=False, key_cert_sign=ca, crl_sign=ca,
                                        encipher_only=False, decipher_only=False)
    ca_key, key = ec.generate_private_key(ec.SECP256R1()), ec.generate_private_key(ec.SECP256R1())
    ca_name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "Test Root"), x509.NameAttribute(NameOID.ORGANIZATION_NAME, "Test")])
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "Test Signer"), x509.NameAttribute(NameOID.ORGANIZATION_NAME, "Test")])
    base = lambda subj, pub: (x509.CertificateBuilder().subject_name(subj).issuer_name(ca_name).public_key(pub)  # noqa: E731
                              .serial_number(x509.random_serial_number()).not_valid_before(now - dt.timedelta(days=1))
                              .not_valid_after(now + dt.timedelta(days=30)))
    ca = (base(ca_name, ca_key.public_key()).add_extension(x509.BasicConstraints(ca=True, path_length=None), critical=True)
          .add_extension(ku(False, True), critical=True).sign(ca_key, hashes.SHA256()))
    leaf = (base(name, key.public_key()).add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
            .add_extension(ku(True, False), critical=True)
            .add_extension(x509.ExtendedKeyUsage([ExtendedKeyUsageOID.EMAIL_PROTECTION]), critical=False)
            .add_extension(x509.AuthorityKeyIdentifier.from_issuer_public_key(ca_key.public_key()), critical=False)
            .add_extension(x509.SubjectKeyIdentifier.from_public_key(key.public_key()), critical=False)
            .sign(ca_key, hashes.SHA256()))
    pem = lambda c: c.public_bytes(serialization.Encoding.PEM)  # noqa: E731
    return pem(leaf) + pem(ca), key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                                  serialization.NoEncryption())


def _signed(source_type: str, generator: str) -> bytes:
    chain, key = _chain()
    manifest = {"claim_generator_info": [{"name": generator, "version": "1"}], "title": "image.jpg",
                "assertions": [{"label": "c2pa.actions", "data": {"actions": [
                    {"action": "c2pa.created", "digitalSourceType": f"http://cv.iptc.org/newscodes/digitalsourcetype/{source_type}"}]}}]}
    signer = c2pa.Signer.from_info(c2pa.C2paSignerInfo(alg=b"es256", sign_cert=chain, private_key=key, ta_url=None))
    out = io.BytesIO()
    c2pa.Builder(json.dumps(manifest)).sign(signer, "image/jpeg", io.BytesIO(_jpeg()), out)
    return out.getvalue()


def test_c2pa_manifest_declaring_ai_is_caught_with_its_generator():
    p = provenance.inspect(_signed("trainedAlgorithmicMedia", "Example Image Model"))
    assert p["c2pa"]["ai"] == "generated by AI" and p["c2pa"]["generator"] == "Example Image Model"
    assert "C2PA content credentials say generated by AI (Example Image Model)" == p["ai"]
    assert forensics.genai_marker(_signed("compositeWithTrainedAlgorithmicMedia", "Editor")) is not None


def test_a_cameras_own_c2pa_signature_is_positive_not_a_flag():
    p = provenance.inspect(_signed("digitalCapture", "Pixel Camera"))
    assert p["ai"] is None and p["c2pa"]["captured"] and p["summary"].startswith("signed by the capturing device")


def test_plain_metadata_markers():
    assert provenance.inspect(_jpeg() + b"<x Iptc4xmpExt:DigitalSourceType='.../trainedAlgorithmicMedia'/>")["ai"]
    png = b"\x89PNG\r\n\x1a\n...tEXtparameters\x00a passport photo, studio light\nSteps: 30, Sampler: DPM++ 2M, CFG scale: 7"
    assert provenance.scan_markers(png) == "stable diffusion parameters"
    assert provenance.scan_markers(b"\xff\xd8 Software: Midjourney v7") == "midjourney"


def test_genuine_photos_are_not_flagged():
    assert provenance.inspect(_jpeg())["ai"] is None
    assert provenance.inspect(_jpeg() + b"<dc:title>Imagen de perfil</dc:title><xmp:CreatorTool>Kreativ Foto</xmp:CreatorTool>")["ai"] is None
    assert provenance.inspect(None)["ai"] is None


def test_a_fully_generated_card_cannot_carry_a_valid_issuer_signature():
    """Even with all metadata stripped: the QR on a generated card is either missing, copied (then the printed details
    and the face won't match it) or signed by a key that isn't the issuer's."""
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
    qr_sign.issuer_key()  # the issuer's public key is published, as on any deployed verifier
    fields = {"n": "SYNTHETIC PERSON", "d": "01/01/1990", "id": "123456789012", "g": "M", "i": "01/01/2020"}
    _, status = qr_sign.parse_and_verify(qr_sign.make_qr_text(fields))
    assert status == qr_sign.VALID  # control: the real issuer's signature verifies
    _, status = qr_sign.parse_and_verify(qr_sign.make_qr_text(fields, key=Ed25519PrivateKey.generate(), kid="attacker"))
    assert status in (qr_sign.UNTRUSTED_KEY, qr_sign.INVALID_SIG)
    _, status = qr_sign.parse_and_verify(qr_sign.make_qr_text(fields, key=Ed25519PrivateKey.generate()))
    assert status == qr_sign.INVALID_SIG



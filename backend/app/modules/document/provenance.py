"""Where did this image come from? Content credentials (C2PA) and AI-provenance metadata.

What major generators attach today:
- Google (Gemini, Imagen) and OpenAI (DALL-E 3, gpt-image), Adobe Firefly, Microsoft Designer / Bing: a signed C2PA
  manifest whose action declares digitalSourceType "trainedAlgorithmicMedia", plus IPTC metadata saying the same.
- Google (and, per Google, OpenAI and other partners) also embed a SynthID pixel watermark, which survives metadata
  stripping. Its detector is not open source: since October 2026 there is a public sign-in web portal (a few checks a
  day) and an enterprise detection API on Google Cloud. Neither is a self-serve API this project can call, so SynthID is
  not checked automatically here; an analyst can upload a suspicious photo to the portal by hand. Wiring the
  enterprise API in would go next to read_c2pa(). The C2PA manifest and IPTC field that generators ship alongside the
  watermark are what we check.
- Local tools (Stable Diffusion web UIs, ComfyUI) write their settings or workflow into PNG text chunks.

All of this is metadata, and an attacker can strip it or simply screenshot the image, so finding it is strong
evidence and NOT finding it proves nothing. The defence that does not depend on metadata is elsewhere: a generated
card cannot carry a valid issuer signature, and a generated face does not match the issuer's photo.
A camera's own C2PA signature ("digitalCapture") is reported as positive provenance, never as a problem.
"""
import io
import json
import re

AI_SOURCE_TYPES = {"trainedalgorithmicmedia": "generated by AI",
                   "compositewithtrainedalgorithmicmedia": "partly generated or edited with AI",
                   "algorithmicmedia": "generated by an algorithm"}
CAPTURE_SOURCE_TYPES = {"digitalcapture", "computationalcapture", "negativefilm", "positivefilm", "print"}

# Generator names and tool fingerprints found in plain metadata (EXIF Software, XMP CreatorTool, PNG text chunks)
GENERATOR_MARKERS = (b"midjourney", b"dall-e", b"dall\xc2\xb7e", b"stable diffusion", b"stablediffusion", b"adobe firefly",
                     b"gpt-image", b"chatgpt", b"google imagen", b"imagen 3", b"imagen 4", b"google gemini",
                     b"made with google ai", b"flux.1", b"ideogram", b"leonardo.ai", b"bing image creator",
                     b"microsoft designer", b"imagine with meta", b"recraft", b"krea.ai", b"playground ai", b"novelai",
                     b"dreamstudio", b"nightcafe", b"craiyon", b"comfyui", b"automatic1111", b"ai generated", b"ai-generated")
# (Kept specific on purpose: bare words such as "imagen" (Spanish for "image") or "krea" ("kreativ") turn up in
# genuine camera metadata.)
# Stable Diffusion web UI writes its generation settings into a PNG "parameters" text chunk
SD_PARAMETERS = re.compile(rb"parameters\x00[^\x00]{0,4000}?(steps: \d+.{0,200}?sampler|cfg scale)", re.I | re.S)
SCAN_BYTES = 1 << 20  # metadata lives near the start of JPEG/PNG/WebP files; 1 MB also covers large XMP packets


def _mime(raw: bytes) -> str | None:
    if raw[:3] == b"\xff\xd8\xff":
        return "image/jpeg"
    if raw[:8] == b"\x89PNG\r\n\x1a\n":
        return "image/png"
    if raw[:4] == b"RIFF" and raw[8:12] == b"WEBP":
        return "image/webp"
    if raw[4:12] in (b"ftypheic", b"ftypheix", b"ftypmif1", b"ftypavif"):
        return "image/heic" if b"heic" in raw[4:12] or b"mif1" in raw[4:12] else "image/avif"
    return None


def _src_type(v: str | None) -> str:
    return (v or "").rstrip("/").rsplit("/", 1)[-1].lower()


def read_c2pa(raw: bytes) -> dict | None:
    """The active C2PA manifest, summarised. None when there is none (or the c2pa library is not installed)."""
    mime = _mime(raw)
    if not mime or b"c2pa" not in raw[:SCAN_BYTES].lower() and b"jumb" not in raw[:SCAN_BYTES]:
        return None
    try:
        import c2pa
        r = c2pa.Reader(mime, io.BytesIO(raw))
        store = json.loads(r.json())
        state = r.get_validation_state()
    except Exception:  # no manifest, unsupported format, or the library is missing
        return None
    m = (store.get("manifests") or {}).get(store.get("active_manifest") or "")
    if not m:
        return None
    actions = [a for x in m.get("assertions", []) if x.get("label", "").startswith("c2pa.actions")
               for a in (x.get("data") or {}).get("actions", [])]
    types = [_src_type(a.get("digitalSourceType")) for a in actions if a.get("digitalSourceType")]
    gen = m.get("claim_generator_info") or []
    generator = ", ".join(g.get("name", "") for g in gen if g.get("name")) or m.get("claim_generator") or None
    sig = m.get("signature_info") or {}
    return {"generator": generator, "signed_by": sig.get("issuer") or sig.get("common_name"),
            "actions": [a.get("action") for a in actions], "source_types": types,
            "ai": next((AI_SOURCE_TYPES[t] for t in types if t in AI_SOURCE_TYPES), None),
            "captured": any(t in CAPTURE_SOURCE_TYPES for t in types),
            "validation": state}


def scan_markers(raw: bytes) -> str | None:
    """A generator name, an IPTC AI source type or Stable Diffusion settings in the file's plain metadata."""
    blob = raw[:SCAN_BYTES]
    low = blob.lower()
    for t, words in AI_SOURCE_TYPES.items():
        if t.encode() in low:
            return t
    if SD_PARAMETERS.search(blob):
        return "stable diffusion parameters"
    return next((m.decode("utf-8", "ignore") for m in GENERATOR_MARKERS if m in low), None)


def inspect(raw: bytes | None) -> dict:
    """{'ai': why or None, 'c2pa': manifest summary or None, 'marker': plain-metadata hit or None, 'summary': text}"""
    if not raw:
        return {"ai": None, "c2pa": None, "marker": None, "summary": "no file"}
    c = read_c2pa(raw)
    marker = scan_markers(raw)
    if c and c["ai"]:
        why = f"C2PA content credentials say {c['ai']}" + (f" ({c['generator']})" if c["generator"] else "")
    elif marker:
        why = f"metadata names an AI source ({marker})"
    else:
        why = None
    if why:
        summary = why
    elif c and c["captured"]:
        summary = f"signed by the capturing device ({c['generator'] or c['signed_by'] or 'camera'})"
    elif c:
        summary = "has content credentials, no AI declared"
    else:
        summary = "no provenance metadata (this proves nothing either way)"
    return {"ai": why, "c2pa": c, "marker": marker, "summary": summary}
